/** Collections --reset deletes everything from — see the file header for why these six specifically. */
const RESET_COLLECTIONS = ["issues", "inspections", "workOrders", "maintenanceRecords", "alerts", "auditLogs"];

function loadServiceAccount(): ServiceAccount {
  if (!fs.existsSync(SERVICE_ACCOUNT_PATH)) {
    console.error(
      `Missing service account key at ${SERVICE_ACCOUNT_PATH}\n\n` +
        "Download one from Firebase Console -> Project settings -> Service accounts\n" +
        "-> Generate new private key, and save it as serviceAccountKey.json in the\n" +
        "project root."
    );
    process.exit(1);
  }
  return JSON.parse(fs.readFileSync(SERVICE_ACCOUNT_PATH, "utf-8"));
}

function getCliArgs(): { officerUid: string; fleetManagerUid: string; officer2Uid: string; reset: boolean } {
  const args = process.argv.slice(2);
  const reset = args.includes("--reset");
  const [officerUid, fleetManagerUid, officer2Uid] = args.filter((arg) => arg !== "--reset");

  if (!officerUid || !fleetManagerUid || !officer2Uid) {
    console.error(
      "Usage: npm run seed -- [--reset] <officerUid> <fleetManagerUid> <officer2Uid>\n\n" +
        "All three are required Firebase Auth UIDs (Firebase Console -> Authentication\n" +
        "-> that user's row) for three distinct, already-existing accounts. Each one is\n" +
        "looked up via Admin Auth before anything is written — see resolveSeedUsers.\n\n" +
        "--reset deletes the demo org's issues/inspections/workOrders/maintenanceRecords/\n" +
        "alerts/auditLogs first (org/users/vehicles/templates are left intact) — see\n" +
        "runReset. Prints what it will delete and requires typing \"yes\" to confirm."
    );
    process.exit(1);
  }
  return { officerUid, fleetManagerUid, officer2Uid, reset };
}

/** Turns "k.ramirez" (from k.ramirez@tulsaexample.gov) into "K Ramirez". */
function deriveNameFromEmail(email: string): { firstName: string; lastName: string } {
  const localPart = email.split("@")[0] ?? email;
  const tokens = localPart
    .split(/[._-]+/)
    .filter(Boolean)
    .map((token) => token.charAt(0).toUpperCase() + token.slice(1));

  if (tokens.length === 0) {
    return { firstName: email, lastName: "" };
  }
  if (tokens.length === 1) {
    return { firstName: tokens[0], lastName: "" };
  }
  return { firstName: tokens[0], lastName: tokens.slice(1).join(" ") };
}

/**
 * Resolves a display name for a seeded user: the Auth account's real
 * `displayName` if it has one, split into first/last on the first space;
 * otherwise something readable derived from the email — never an
 * invented persona unrelated to who's actually signing in.
 */
function resolveDisplayName(record: UserRecord): { firstName: string; lastName: string } {
  const displayName = record.displayName?.trim();
  if (displayName) {
    const [firstName, ...rest] = displayName.split(/\s+/);
    return { firstName, lastName: rest.join(" ") };
  }
  return deriveNameFromEmail(record.email ?? record.uid);
}

interface ResolvedSeedUser {
  uid: string;
  role: UserRole;
  email: string;
  firstName: string;
  lastName: string;
}

/**
 * Looks up all three UIDs via Admin Auth, prints "UID -> email" for each,
 * and refuses to write anything to Firestore if any lookup fails (wrong
 * UID, deleted account, or an account with no email) — the whole reason
 * the previous run seeded k.ramirez@tulsaexample.gov's real account as
 * "Alex Rivera / fleet_manager" is that nothing ever verified a UID
 * actually belonged to the identity it was about to be labeled with.
 * Role assignment stays positional (officerUid/officer2Uid -> "officer",
 * fleetManagerUid -> "fleet_manager") — that's the one thing the caller
 * is genuinely choosing; name and email always come from the real account.
 */
async function resolveSeedUsers(uids: {
  officerUid: string;
  fleetManagerUid: string;
  officer2Uid: string;
}): Promise<ResolvedSeedUser[]> {
  const auth = getAuth();
  const requests: Array<{ label: string; uid: string; role: UserRole }> = [
    { label: "officerUid", uid: uids.officerUid, role: "officer" },
    { label: "fleetManagerUid", uid: uids.fleetManagerUid, role: "fleet_manager" },
    { label: "officer2Uid", uid: uids.officer2Uid, role: "officer" },
  ];

  console.log("Verifying UIDs against Firebase Auth:");
  const results = await Promise.allSettled(requests.map((r) => auth.getUser(r.uid)));

  let hasFailure = false;
  const resolved: ResolvedSeedUser[] = [];

  results.forEach((result, index) => {
    const request = requests[index];
    if (result.status === "rejected") {
      hasFailure = true;
      const message = result.reason instanceof Error ? result.reason.message : String(result.reason);
      console.error(`  ${request.label} (${request.uid}) -> LOOKUP FAILED: ${message}`);
      return;
    }
    const record = result.value;
    if (!record.email) {
      hasFailure = true;
      console.error(`  ${request.label} (${request.uid}) -> account has no email; can't seed a profile for it.`);
      return;
    }
    console.log(`  ${request.label} (${request.uid}) -> ${record.email}`);
    const { firstName, lastName } = resolveDisplayName(record);
    resolved.push({ uid: request.uid, role: request.role, email: record.email, firstName, lastName });
  });

  if (hasFailure) {
    console.error("\nAborting: one or more UIDs failed verification. Nothing was written.");
    process.exit(1);
  }

  return resolved;
}

/** Prompts on stdin and returns true only if the typed answer is exactly "yes" (case-insensitive). */
async function promptYesNo(question: string): Promise<boolean> {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  try {
    const answer = await rl.question(question);
    return answer.trim().toLowerCase() === "yes";
  } finally {
    rl.close();
  }
}

/** Deletes every given document ref, batching in chunks of 500 (Firestore's per-batch write limit). */
async function deleteRefs(db: Firestore, refs: DocumentReference[]): Promise<void> {
  for (let i = 0; i < refs.length; i += 500) {
    const chunk = refs.slice(i, i + 500);
    const batch = db.batch();
    chunk.forEach((ref) => batch.delete(ref));
    await batch.commit();
  }
}

/**
 * Deletes every document under organizations/{ORG_ID}'s
 * issues/inspections/workOrders/maintenanceRecords/alerts/auditLogs
 * collections. Leaves organizations/{ORG_ID} itself, and its
 * users/vehicles/inspectionTemplates subcollections, completely
 * untouched. Prints exactly what it's about to delete and requires
 * typing "yes" before doing anything irreversible; the caller (main)
 * exits without reseeding if the answer isn't "yes".
 */
async function runReset(db: Firestore): Promise<void> {
  console.log(`\nCounting documents to delete under organizations/${ORG_ID}:`);

  const refsByCollection = new Map<string, DocumentReference[]>();
  let total = 0;
  for (const collectionName of RESET_COLLECTIONS) {
    const refs = await db.collection(`organizations/${ORG_ID}/${collectionName}`).listDocuments();
    refsByCollection.set(collectionName, refs);
    total += refs.length;
    console.log(`  ${collectionName}: ${refs.length} document(s)`);
  }

  if (total === 0) {
    console.log("\nNothing to delete.\n");
    return;
  }

  console.log(
    `\nThis will PERMANENTLY delete ${total} document(s) listed above from organizations/${ORG_ID}.\n` +
      `organizations/${ORG_ID} itself, and its users/vehicles/inspectionTemplates subcollections, are NOT touched.`
  );
  const confirmed = await promptYesNo('\nType "yes" to permanently delete these documents, or anything else to cancel: ');
  if (!confirmed) {
    console.log("\nAborted — nothing was deleted, and the reseed did not run.");
    process.exit(0);
  }

  console.log("\nDeleting:");
  for (const collectionName of RESET_COLLECTIONS) {
    const refs = refsByCollection.get(collectionName) ?? [];
    if (refs.length > 0) {
      await deleteRefs(db, refs);
    }
    console.log(`  ${collectionName}: deleted ${refs.length} document(s)`);
  }
  console.log("");
}

/**
 * Returns `fields` if `ref`'s document doesn't exist yet, else `{}`.
 * Use this for fields the live app/Cloud Functions also mutate (vehicle
 * `status`, issue `status`) so re-running this idempotent seed only ever
 * sets an initial value — it never stomps on real, already-tested state
 * from a previous run.
 */
async function onlyOnFirstCreate(
  ref: DocumentReference,
  fields: Record<string, unknown>
): Promise<Record<string, unknown>> {
  const snap = await ref.get();
  return snap.exists ? {} : fields;
}

function daysAgoTimestamp(days: number): Timestamp {
  return Timestamp.fromDate(new Date(Date.now() - days * 24 * 60 * 60 * 1000));
}

/**
 * The six-item daily vehicle inspection checklist, in the canonical
 * `TemplateItem` shape (src/types) — every item is a pass/fail check,
 * required, and auto-creates an Issue on failure. `requiresPhoto`/
 * `requiresNote` make a note/photo *mandatory* on a given item (a note
 * and a photo upload are always available on every item regardless — see
 * src/app/inspections/new/page.tsx); no seeded item sets either flag
 * today, but the enforcement stays wired for when a department wants
 * mandatory evidence on a specific item (a damaged tire, a cracked
 * windshield).
 */
const CHECKLIST_ITEMS: Array<Pick<TemplateItem, "id" | "label" | "requiresPhoto" | "requiresNote">> = [
  { id: "tires", label: "Tires", requiresPhoto: false, requiresNote: false },
  { id: "brakes", label: "Brakes", requiresPhoto: false, requiresNote: false },
  { id: "lights", label: "Lights", requiresPhoto: false, requiresNote: false },
  { id: "emergency-light", label: "Emergency Lights", requiresPhoto: false, requiresNote: false },
  { id: "siren", label: "Siren", requiresPhoto: false, requiresNote: false },
  { id: "radio", label: "Radio", requiresPhoto: false, requiresNote: false },
];

const DAILY_INSPECTION_ITEMS: TemplateItem[] = CHECKLIST_ITEMS.map((item, index) => ({
  ...item,
  templateId: TEMPLATE_ID,
  sortOrder: index,
  section: item.label,
  responseType: "pass_fail",
  isRequired: true,
  autoCreateIssueOnFail: true,
}));

/** Builds an all-items-passed response set for a seeded completed inspection. */
function buildPassingItems(inspectionId: string, respondedAt: Timestamp): InspectionItemResult[] {
  return CHECKLIST_ITEMS.map((item) => ({
    id: `${inspectionId}-${item.id}`,
    inspectionId,
    templateItemId: item.id,
    itemLabel: item.label,
    passed: true,
    textValue: "",
    respondedAt: respondedAt.toDate().toISOString(),
  }));
}

